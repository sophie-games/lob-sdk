const fs = require("node:fs");
const path = require("node:path");

const erasDirectory = path.resolve(__dirname, "../src/game-data/eras");

const scenarioEntries = (catalogSource) => {
  const imports = new Map();
  const importPattern =
    /import\s+(\w+)\s+from\s+"\.\/scenarios\/([^"]+)\.json";/g;
  for (const match of catalogSource.matchAll(importPattern)) {
    imports.set(match[1], match[2]);
  }

  const catalogBody = catalogSource.match(
    /export const \w+ScenarioCatalog = \{([\s\S]*?)\}\s+as unknown as ScenarioCatalog;/,
  )?.[1];
  if (!catalogBody) {
    throw new Error("Could not find the scenario catalog object");
  }

  return catalogBody
    .split("\n")
    .map((line) => line.trim().replace(/,$/, ""))
    .filter(Boolean)
    .map((entry) => {
      const explicit = entry.match(/^"([^"]+)":\s*(\w+)$/);
      const shorthand = entry.match(/^(\w+)$/);
      const scenarioName = explicit?.[1] ?? shorthand?.[1];
      const importName = explicit?.[2] ?? shorthand?.[1];
      const fileName = importName ? imports.get(importName) : undefined;

      if (!scenarioName || !fileName) {
        throw new Error(`Could not parse scenario catalog entry: ${entry}`);
      }
      return { scenarioName, fileName };
    });
};

for (const era of fs.readdirSync(erasDirectory).sort()) {
  const eraDirectory = path.join(erasDirectory, era);
  const catalogPath = path.join(eraDirectory, "scenario-catalog.ts");
  if (!fs.existsSync(catalogPath)) continue;

  const entries = scenarioEntries(fs.readFileSync(catalogPath, "utf8"));
  const index = Object.fromEntries(
    entries.map(({ scenarioName, fileName }) => {
      const scenario = JSON.parse(
        fs.readFileSync(
          path.join(eraDirectory, "scenarios", `${fileName}.json`),
          "utf8",
        ),
      );
      const mapSize = scenario.map
        ? { width: scenario.map.width, height: scenario.map.height }
        : (scenario.fixedSize ?? null);
      const locales = scenario.locales
        ? Object.fromEntries(
            Object.entries(scenario.locales).map(([language, values]) => [
              language,
              Object.fromEntries(
                ["name", "description"]
                  .filter((key) => values[key] !== undefined)
                  .map((key) => [key, values[key]]),
              ),
            ]),
          )
        : undefined;

      return [
        scenarioName,
        {
          name: scenario.name,
          description: scenario.description,
          locales,
          ranked: scenario.ranked ?? false,
          hidden: scenario.hidden ?? false,
          playerCount: Array.isArray(scenario.players)
            ? scenario.players.length
            : null,
          mapSize,
        },
      ];
    }),
  );

  const exportName = `${era.replace(/-([a-z])/g, (_, letter) =>
    letter.toUpperCase(),
  )}ScenarioIndex`;
  const output = `// Generated by scripts/generate-scenario-index.cjs. Do not edit.\nimport type { ScenarioIndex } from "@lob-sdk/game-data-manager/scenario-index";\n\nexport const ${exportName}: ScenarioIndex = ${JSON.stringify(index, null, 2)};\n`;
  fs.writeFileSync(path.join(eraDirectory, "scenario-index.ts"), output);
}
